import { createRequire } from 'node:module';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:4173';
const output = process.env.QA_OUTPUT || 'artifacts/access-menu';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
const errors = [], results = [];
const check = name => results.push({ test: name, passed: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.goto(base);
  const root = page.locator('.header-actions [data-system-access]');
  const link = root.locator('.system-access-link');
  const toggle = root.locator('button');
  const panel = root.locator('.system-dropdown');
  const isOpen = () => toggle.getAttribute('aria-expanded');
  await link.hover();
  await page.waitForTimeout(200);
  assert.equal(await isOpen(), 'true');
  assert.equal(await panel.evaluate(el => getComputedStyle(el).transitionDuration.split(', ')[0]), '0.18s');
  const bounds = await link.boundingBox();
  await page.mouse.move(bounds.x + 40, bounds.y + bounds.height + 5, { steps: 6 });
  assert.equal(await isOpen(), 'true', 'O espaço entre botão e painel não pode fechar o dropdown');
  await panel.getByRole('link', { name: 'Acessar BarberHub' }).hover();
  assert.equal(await isOpen(), 'true');
  await page.screenshot({ path: `${output}/dropdown-desktop.png` });
  check('hover-e-travessia-sem-fechamento');
  assert.equal(await panel.locator('[aria-disabled="true"]').count(), 5);
  assert.equal(await panel.locator('a').count(), 1);
  assert.equal(await panel.locator('a').getAttribute('href'), 'https://barberhub.navorbr.com/barber');
  await panel.getByText('LawHub', { exact: true }).click();
  assert.equal(new URL(page.url()).pathname, '/');
  check('somente-barberhub-operacional');
  await page.mouse.move(30, 300);
  assert.equal(await isOpen(), 'false');
  await page.waitForTimeout(160);
  assert.equal(await panel.evaluate(el => getComputedStyle(el).transitionDuration.split(', ')[0]), '0.14s');
  assert.equal(await panel.evaluate(el => getComputedStyle(el).visibility), 'hidden');
  check('saida-do-ponteiro-fecha');
  await toggle.focus();
  await page.keyboard.press('Enter');
  assert.equal(await isOpen(), 'true');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.href), 'https://barberhub.navorbr.com/barber');
  await page.keyboard.press('Escape');
  assert.equal(await isOpen(), 'false');
  assert.ok(await toggle.evaluate(el => el === document.activeElement));
  await page.keyboard.press('Space');
  assert.equal(await isOpen(), 'true');
  await page.locator('h1').click();
  assert.equal(await isOpen(), 'false');
  await toggle.focus(); await page.keyboard.press('ArrowDown');
  assert.equal(await page.evaluate(() => document.activeElement.href), 'https://barberhub.navorbr.com/barber');
  await page.keyboard.press('Tab');
  assert.equal(await isOpen(), 'false');
  check('teclado-escape-clique-fora-e-tab');
  // Verify the exact requested navigation without submitting anything to a product.
  const destinations = [];
  await page.route('https://barberhub.navorbr.com/barber', route => {
    destinations.push(route.request().url());
    return route.fulfill({ status: 200, contentType: 'text/html', body: '<title>Navigation target checked</title>' });
  });
  await toggle.click();
  await panel.getByRole('link', { name: 'Acessar BarberHub' }).click();
  assert.deepEqual(destinations, ['https://barberhub.navorbr.com/barber']);
  check('clique-barberhub-envia-para-barber');
  await page.goto(base);
  await link.click();
  await page.waitForURL(`${base}/acessar`);
  assert.equal(await page.locator('h1').textContent(), 'Qual sistema deseja acessar?');
  check('clique-principal-acessar');
  const requests = [];
  page.on('request', r => requests.push(r.url()));
  const direct = await page.goto(`${base}/acessar`);
  assert.equal(direct.status(), 200);
  assert.equal((await page.reload()).status(), 200);
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('.access-card').count(), 6);
  assert.equal(await page.locator('h1').evaluate(el => getComputedStyle(el).animationDuration), '0.55s');
  assert.equal(await page.locator('.access-subtitle').evaluate(el => getComputedStyle(el).animationDuration), '0.45s');
  assert.deepEqual(await page.locator('.access-card').evaluateAll(els => els.map(el => getComputedStyle(el).animationDelay)), ['0s','0.07s','0.14s','0.21s','0.28s','0.35s']);
  assert.equal(await page.locator('.access-card a').count(), 1);
  assert.equal(await page.getByRole('link', { name: 'Acessar BarberHub', exact: true }).getAttribute('href'), 'https://barberhub.navorbr.com/barber');
  assert.equal(await page.locator('canvas').count(), 0);
  assert.ok(!requests.some(url => /\/(main|globe)\.js|earth-night/.test(url)));
  check('rota-direta-refresh-seis-cards-sem-globo');
  const activeCard = page.locator('.access-card-available');
  await activeCard.hover(); await page.waitForTimeout(240);
  assert.equal(await activeCard.evaluate(el => getComputedStyle(el).transform), 'matrix(1, 0, 0, 1, 0, -5)');
  assert.equal(await activeCard.evaluate(el => getComputedStyle(el, '::before').opacity), '1');
  await page.locator('.access-card').nth(1).hover(); await page.waitForTimeout(240);
  assert.equal(await page.locator('.access-card').nth(1).evaluate(el => getComputedStyle(el).transform), 'none');
  check('hover-apenas-no-card-disponivel');
  for (const width of [360,390,768,1024,1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(`${base}/acessar`); await page.waitForTimeout(1200);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('footer').scrollIntoViewIfNeeded();
    await page.evaluate(() => scrollTo(0,0)); await page.waitForTimeout(100);
    await page.screenshot({ path: `${output}/acessar-${width}.png`, fullPage: true });
  }
  check('responsividade-360-a-1440');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const touch = await mobile.newPage();
  touch.on('pageerror', e => errors.push(e.message));
  await touch.goto(base);
  await touch.getByRole('button', { name: 'Abrir menu', exact: true }).tap();
  const dialog = touch.getByRole('dialog');
  const mobileToggle = dialog.getByRole('button', { name: 'Mostrar sistemas' });
  await mobileToggle.tap();
  assert.equal(await mobileToggle.getAttribute('aria-expanded'), 'true');
  await touch.waitForTimeout(200);
  assert.equal(await dialog.locator('.system-option').count(), 6);
  assert.ok(await dialog.getByRole('link', { name: 'Acessar BarberHub', exact: true }).isVisible());
  await touch.screenshot({ path: `${output}/dropdown-mobile.png` });
  await touch.keyboard.press('Escape');
  assert.equal(await mobileToggle.getAttribute('aria-expanded'), 'false');
  assert.ok(await dialog.isVisible());
  await mobileToggle.tap(); await mobileToggle.tap();
  assert.equal(await mobileToggle.getAttribute('aria-expanded'), 'false');
  await dialog.getByRole('link', { name: 'Acessar sistema', exact: true }).tap();
  await touch.waitForURL(`${base}/acessar`);
  assert.ok(await touch.locator('h1').isVisible());
  check('mobile-toque-controle-separado-e-acessar');
  await mobile.close();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(`${base}/acessar`);
  assert.equal(await page.locator('h1').evaluate(el => getComputedStyle(el).animationName), 'none');
  await toggle.click();
  assert.equal(await panel.evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await activeCard.hover();
  assert.equal(await activeCard.evaluate(el => getComputedStyle(el).transform), 'none');
  check('movimento-reduzido');
  const noJs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  const staticPage = await noJs.newPage();
  await staticPage.goto(`${base}/acessar`);
  assert.equal(await staticPage.locator('.access-card').count(), 6);
  assert.ok(await staticPage.getByRole('link', { name: 'Acessar BarberHub', exact: true }).isVisible());
  await noJs.close();
  check('conteudo-publico-sem-javascript');
  const source = await readFile('index.html', 'utf8');
  const previous = execFileSync('git', ['show', 'HEAD:index.html'], { encoding: 'utf8' });
  const main = html => html.match(/<main[\s\S]*?<\/main>/)[0].replaceAll('\r\n','\n');
  assert.equal(main(source), main(previous), 'Conteúdo da homepage alterado fora do cabeçalho');
  assert.equal(execFileSync('git',['diff','--','globe.js','styles.css'],{encoding:'utf8'}),'');
  check('hero-produtos-globo-e-estilos-originais-preservados');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ results, errors }, null, 2));
} finally {
  await writeFile(`${output}/access-results.json`, JSON.stringify({ results, errors }, null, 2));
  await browser.close();
}
